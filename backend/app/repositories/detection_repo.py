"""Database repository for detection assessments, alerts, and investigation transitions."""

from __future__ import annotations

import logging
from datetime import datetime, timezone
from typing import Any

from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession
from sqlalchemy.orm import selectinload

from app.db.models.detection import AlertEventModel, AlertModel, AssessmentModel
from app.db.session import get_session

logger = logging.getLogger("sentinel_flow.repositories.detection")


class DetectionRepository:
    """Manages database persistence for multi-layer anomaly assessments and alert lifecycles."""

    async def save_assessment(
        self,
        identity_id: str,
        threat_score: float,
        threat_level: str,
        rule_score: float,
        ml_score: float,
        flow_score: float,
        fused_score: float,
        model_version: str = "v1.0",
        matched_rules: list[Any] | None = None,
        explanation_json: dict[str, Any] | None = None,
        ts: datetime | None = None,
    ) -> AssessmentModel:
        """Store fused multi-layer assessment."""
        record = AssessmentModel(
            identity_id=identity_id,
            threat_score=threat_score,
            threat_level=threat_level,
            rule_score=rule_score,
            ml_score=ml_score,
            flow_score=flow_score,
            fused_score=fused_score,
            model_version=model_version,
            matched_rules=matched_rules,
            explanation_json=explanation_json,
            ts=ts or datetime.now(timezone.utc),
        )
        async with get_session() as session:
            session.add(record)
            await session.flush()
            return record

    async def get_latest_assessment(self, identity_id: str) -> AssessmentModel | None:
        """Fetch newest assessment for an identity."""
        async with get_session() as session:
            stmt = (
                select(AssessmentModel)
                .where(AssessmentModel.identity_id == identity_id)
                .order_by(AssessmentModel.ts.desc())
                .limit(1)
            )
            result = await session.execute(stmt)
            return result.scalar_one_or_none()

    async def get_all_latest_assessments(self) -> list[AssessmentModel]:
        """Fetch latest assessment across all monitored identities."""
        async with get_session() as session:
            # Subquery or ordered fetch
            stmt = select(AssessmentModel).order_by(AssessmentModel.ts.desc()).limit(100)
            result = await session.execute(stmt)
            seen: set[str] = set()
            latest: list[AssessmentModel] = []
            for item in result.scalars().all():
                if item.identity_id not in seen:
                    seen.add(item.identity_id)
                    latest.append(item)
            return latest

    async def save_alert(
        self,
        alert_id: str,
        identity_id: str,
        rule_id: str,
        name: str,
        severity: str,
        threat_score: float,
        status: str = "open",
        evidence_json: list[Any] | dict[str, Any] | None = None,
        session_id: str | None = None,
        analyst: str | None = None,
    ) -> AlertModel:
        """Create or update security alert in database."""
        async with get_session() as session:
            stmt = select(AlertModel).where(AlertModel.alert_id == alert_id)
            result = await session.execute(stmt)
            record = result.scalar_one_or_none()

            if record is None:
                record = AlertModel(
                    alert_id=alert_id,
                    identity_id=identity_id,
                    rule_id=rule_id,
                    name=name,
                    severity=severity,
                    threat_score=threat_score,
                    status=status,
                    evidence_json=evidence_json,
                    session_id=session_id,
                    analyst=analyst,
                )
                session.add(record)
                # Create initial transition event
                transition = AlertEventModel(
                    alert_id=alert_id,
                    action="create",
                    from_status="none",
                    to_status=status,
                    analyst=analyst or "system",
                    notes="Alert generated by detection engine",
                )
                session.add(transition)
            else:
                record.threat_score = threat_score
                record.severity = severity
                record.evidence_json = evidence_json

            await session.flush()
            return record

    async def transition_alert_status(
        self,
        alert_id: str,
        to_status: str,
        analyst: str = "operator",
        notes: str | None = None,
    ) -> AlertModel | None:
        """Transition alert state machine and write immutable audit event."""
        valid_transitions = {
            "open": ["acknowledged", "investigating", "resolved", "false_positive"],
            "acknowledged": ["investigating", "resolved", "false_positive"],
            "investigating": ["resolved", "false_positive"],
            "resolved": ["investigating", "open"],
            "false_positive": ["investigating", "open"],
        }

        async with get_session() as session:
            stmt = select(AlertModel).where(AlertModel.alert_id == alert_id)
            result = await session.execute(stmt)
            alert = result.scalar_one_or_none()
            if not alert:
                return None

            from_status = alert.status
            alert.status = to_status
            alert.analyst = analyst
            if notes:
                alert.analyst_notes = notes
            if to_status in ("resolved", "false_positive"):
                alert.resolved_at = datetime.now(timezone.utc)

            transition = AlertEventModel(
                alert_id=alert_id,
                action="status_change",
                from_status=from_status,
                to_status=to_status,
                analyst=analyst,
                notes=notes,
            )
            session.add(transition)
            await session.flush()
            return alert

    async def get_alerts(
        self,
        status: str | None = None,
        limit: int = 100,
    ) -> list[AlertModel]:
        """Fetch alerts with transitions preloaded."""
        async with get_session() as session:
            stmt = select(AlertModel).options(selectinload(AlertModel.events))
            if status:
                stmt = stmt.where(AlertModel.status == status)
            stmt = stmt.order_by(AlertModel.created_at.desc()).limit(limit)
            result = await session.execute(stmt)
            return list(result.scalars().all())
