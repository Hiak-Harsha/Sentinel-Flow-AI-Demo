"""Telemetry Engine: aggregates raw device requests into network-flow metrics."""

from __future__ import annotations

import time
from collections import deque
from datetime import datetime, timezone
from typing import Any


def _timestamp() -> str:
    return datetime.now(timezone.utc).isoformat().replace("+00:00", "Z")


class TelemetryService:
    def __init__(self, history_limit: int = 120) -> None:
        self.request_records: deque[dict[str, Any]] = deque(maxlen=2000)
        self.timeseries_history: deque[dict[str, Any]] = deque(maxlen=history_limit)
        self.baseline_samples: list[dict[str, float]] = []
        self.device_last_times: dict[str, float] = {}
        self.baseline_established = False

    def record_request(
        self,
        device_id: str,
        action: str,
        bytes_in: int = 128,
        bytes_out: int = 1024,
    ) -> dict[str, Any]:
        """Record an actual request generated by an owned client device."""
        now_ts = time.time()
        last_ts = self.device_last_times.get(device_id, now_ts - 0.25)
        inter_arrival_ms = max(5.0, (now_ts - last_ts) * 1000.0)
        self.device_last_times[device_id] = now_ts

        record = {
            "device_id": device_id,
            "action": action,
            "timestamp": now_ts,
            "iso_time": _timestamp(),
            "bytes_in": bytes_in,
            "bytes_out": bytes_out,
            "inter_arrival_ms": inter_arrival_ms,
        }
        self.request_records.append(record)

        # Compute immediate device metrics
        device_metrics = self.compute_device_metrics(device_id)

        # Save sample for baseline if collecting
        if not self.baseline_established and len(self.baseline_samples) < 50:
            self.baseline_samples.append({
                "request_rate": device_metrics["request_rate"],
                "inter_arrival_ms": device_metrics["inter_arrival_ms"],
                "bytes_out": float(bytes_out),
                "burstiness": device_metrics["burstiness"],
            })

        return {
            "record": record,
            "metrics": device_metrics,
        }

    def compute_device_metrics(self, device_id: str) -> dict[str, float]:
        """Calculate live rolling metrics for a specific device."""
        now_ts = time.time()
        window_seconds = 2.0
        recent = [
            r for r in self.request_records
            if r["device_id"] == device_id and (now_ts - r["timestamp"]) <= window_seconds
        ]

        count = len(recent)
        rate = round(count / window_seconds, 2)

        if recent:
            arrivals = [r["inter_arrival_ms"] for r in recent]
            avg_arrival = round(sum(arrivals) / len(arrivals), 1)
            # Burstiness = standard deviation / mean of arrival times
            if len(arrivals) > 2 and avg_arrival > 0:
                variance = sum((x - avg_arrival) ** 2 for x in arrivals) / len(arrivals)
                burstiness = round(min(1.0, (variance ** 0.5) / avg_arrival), 3)
            else:
                burstiness = 0.12
            total_bytes = sum(r["bytes_out"] for r in recent)
        else:
            avg_arrival = 280.0
            burstiness = 0.1
            total_bytes = 0

        return {
            "request_rate": rate,
            "inter_arrival_ms": avg_arrival,
            "burstiness": burstiness,
            "bytes_out": float(total_bytes),
        }

    def compute_network_snapshot(self) -> dict[str, Any]:
        """Generate network-wide telemetry rates across all devices."""
        now_ts = time.time()
        window_seconds = 2.0
        recent = [r for r in self.request_records if (now_ts - r["timestamp"]) <= window_seconds]

        total_requests = len(recent)
        overall_rate = round(total_requests / window_seconds, 1)
        bytes_in = sum(r["bytes_in"] for r in recent)
        bytes_out = sum(r["bytes_out"] for r in recent)
        active_devices = len(set(r["device_id"] for r in recent))

        snapshot = {
            "timestamp": _timestamp(),
            "epoch": now_ts,
            "requests_per_sec": overall_rate,
            "bytes_in_per_sec": round(bytes_in / window_seconds, 1),
            "bytes_out_per_sec": round(bytes_out / window_seconds, 1),
            "active_devices": max(active_devices, 1 if total_requests > 0 else 0),
        }

        self.timeseries_history.append(snapshot)
        return snapshot

    def get_timeseries(self) -> list[dict[str, Any]]:
        return list(self.timeseries_history)

    def get_baseline_samples(self) -> list[dict[str, float]]:
        return self.baseline_samples

    def mark_baseline_ready(self) -> None:
        self.baseline_established = True
